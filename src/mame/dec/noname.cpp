void noname_state::machine_reset()
{
	u8 *const ram = m_ram->pointer();

	// the srom loads palcode and the console into memory before releasing the cpu
	std::copy_n(reinterpret_cast<u8 const *>(&m_palcode[0]), m_palcode.bytes(), ram);
	std::copy_n(reinterpret_cast<u8 const *>(&m_milo[0]), m_milo.bytes(), ram + 0x210000);

	m_ioc_stat0 = 0;

	// the console firmware leaves the interrupt controllers initialised and the
	// rtc generating the 1024Hz periodic interrupt used for the system clock
	m_pic[0]->write(0, 0x11);
	m_pic[0]->write(1, 0x00);
	m_pic[0]->write(1, 0x04);
	m_pic[0]->write(1, 0x01);
	m_pic[0]->write(1, 0x00);

	m_pic[1]->write(0, 0x11);
	m_pic[1]->write(1, 0x08);
	m_pic[1]->write(1, 0x02);
	m_pic[1]->write(1, 0x01);
	m_pic[1]->write(1, 0x00);

	// the slave dma controller is cascaded through channel 0 of the master
	m_dma[1]->write(0x0b, 0xc0);
	m_dma[1]->write(0x0a, 0x00);

	// the console firmware runs the keyboard controller self test, which is
	// what starts it polling the keyboard, and leaves the command byte asking
	// for interrupts and for scan codes translated to the set the host expects
	m_kbdc->data_w(4, 0xaa);
	m_kbdc->data_r(0);
	m_kbdc->data_w(4, 0x60);
	m_kbdc->data_w(0, 0x45);

	vga_post();

	m_rtc->address_w(0x0a);
	m_rtc->data_w(0x26);
	m_rtc->address_w(0x0b);
	m_rtc->data_w(0x40);

}

