void noname_state::local_memory(address_map &map)
{
}

/*
 * Addresses from 0x1'00000000 up appear here without their high bits: memory
 * controller at 0x20000000, i/o controller at 0x80000000, interrupt acknowledge
 * at 0xa0000000, sparse pci i/o at 0xc0000000 and pci configuration at
 * 0xe0000000.
 */
void noname_state::local_io(address_map &map)
{
	// the 21066 has further chipset registers below the memory controller
	map(0x00000000, 0x1fffffff).lrw64(
		NAME([this] (offs_t offset) { return 0ULL; }),
		NAME([this] (offs_t offset, u64 data) { }));

	map(0x20000000, 0x2000ffff).lrw64(
		NAME([this] (offs_t offset) { LOG("mem_r %02x\n", offset); return 0ULL; }),
		NAME([this] (offs_t offset, u64 data) { LOG("mem_w %02x 0x%x\n", offset, data); }));

	map(0x80000000, 0x8000ffff).rw(FUNC(noname_state::ioc_r), FUNC(noname_state::ioc_w));

	map(0xa0000000, 0xa000001f).lr32(
		NAME([this] (offs_t offset)
		{
			return machine().side_effects_disabled()
				? 0xffU : u32(m_pic[0]->acknowledge());
		}));

	map(0xc0000000, 0xdfffffff).rw(FUNC(noname_state::sparse_io_r), FUNC(noname_state::sparse_io_w));

	map(0xe0000000, 0xffffffff).rw(FUNC(noname_state::config_r), FUNC(noname_state::config_w));
}

/*
 * Sparse pci memory. The video card is the only thing on the bus, so everything
 * else reads all ones and swallows what is written to it.
 */
void noname_state::pci_memory(address_map &map)
{
	map(0x00000000, 0xffffffff).lrw32(
		NAME([this] (offs_t offset) { return 0xffffffffU; }),
		NAME([this] (offs_t offset, u32 data, u32 mem_mask) { }));

	// the text and graphics window of the video card, 0xa0000 to 0xbffff
	map(0x01400000, 0x017fffff).rw(FUNC(noname_state::vga_mem_r), FUNC(noname_state::vga_mem_w));
}

void noname_state::vga_io(address_map &map)
{
	map(0x00, 0x2f).m(m_vga, FUNC(vga_device::io_map));
}

/*
 * Sparse addressing encodes the width of the transfer in the low address bits:
 * zero for a byte, two for a word and six for a longword, and the data sits in
 * the byte lanes selected by the low bits of the target address.
 */
static unsigned sparse_count(offs_t offset)
{
	unsigned const code = offset & 7;

	return (code < 2) ? 1 : ((code < 6) ? 2 : 4);
}

u32 noname_state::vga_mem_r(offs_t offset, u32 mem_mask)
{
	offs_t const addr = offset >> 3;
	unsigned const lane = (addr & 3) * 8;
	unsigned const count = sparse_count(offset);
	u32 data = 0;

	for (unsigned i = 0; i < count; i++)
		data |= u32(m_vga->mem_r(addr + i)) << (lane + i * 8);

	return data;
}

void noname_state::vga_mem_w(offs_t offset, u32 data, u32 mem_mask)
{
	offs_t const addr = offset >> 3;
	unsigned const lane = (addr & 3) * 8;
	unsigned const count = sparse_count(offset);

	for (unsigned i = 0; i < count; i++)
		m_vga->mem_w(addr + i, u8(data >> (lane + i * 8)));
}

u64 noname_state::ioc_r(offs_t offset)
{
	switch (offset * 8)
	{
	case 0x00: return m_ioc_hae;
	case 0x20: return m_ioc_conf;
	case 0x40: return m_ioc_stat0;
	case 0x60: return m_ioc_stat1;
	default:
		return 0;
	}
}

void noname_state::ioc_w(offs_t offset, u64 data)
{
	switch (offset * 8)
	{
	case 0x00: m_ioc_hae = data; break;
	case 0x20: m_ioc_conf = data; break;

		// status bits are cleared by writing them back
	case 0x40: m_ioc_stat0 &= ~data; break;
	case 0x60: m_ioc_stat1 &= ~data; break;

	default:
		break;
	}
}

/*
 * Nothing is fitted on the pci bus yet, so configuration cycles terminate in a
 * master abort, which is what the miniloader expects when probing empty slots.
 */
u32 noname_state::config_r(offs_t offset)
{
	if (!machine().side_effects_disabled())
		m_ioc_stat0 |= STAT0_ERR | (1U << 8);

	return 0xffffffffU;
}

void noname_state::config_w(offs_t offset, u32 data)
{
	m_ioc_stat0 |= STAT0_ERR | (1U << 8);
}

u8 noname_state::dma_page_r(unsigned port)
{
	switch (port)
	{
	case 0x87: return m_dma[0]->get_address_page<0>();
	case 0x83: return m_dma[0]->get_address_page<1>();
	case 0x81: return m_dma[0]->get_address_page<2>();
	case 0x82: return m_dma[0]->get_address_page<3>();
	case 0x8b: return m_dma[1]->get_address_page<1>();
	case 0x89: return m_dma[1]->get_address_page<2>();
	case 0x8a: return m_dma[1]->get_address_page<3>();
	default: return 0;
	}
}

void noname_state::dma_page_w(unsigned port, u8 data)
{
	switch (port)
	{
	case 0x87: m_dma[0]->set_address_page<0>(data); break;
	case 0x83: m_dma[0]->set_address_page<1>(data); break;
	case 0x81: m_dma[0]->set_address_page<2>(data); break;
	case 0x82: m_dma[0]->set_address_page<3>(data); break;
	case 0x8b: m_dma[1]->set_address_page<1>(data); break;
	case 0x89: m_dma[1]->set_address_page<2>(data); break;
	case 0x8a: m_dma[1]->set_address_page<3>(data); break;
	default: break;
	}
}

u8 noname_state::fdc_r(unsigned reg)
{
	switch (reg)
	{
	case 0: return m_fdc->sra_r();
	case 1: return m_fdc->srb_r();
	case 2: return m_fdc->dor_r();
	case 3: return m_fdc->tdr_r();
	case 4: return m_fdc->msr_r();
	case 5: return m_fdc->fifo_r();
	case 7: return m_fdc->dir_r();
	default: return 0;
	}
}

void noname_state::fdc_w(unsigned reg, u8 data)
{
	switch (reg)
	{
	case 2: m_fdc->dor_w(data); break;
	case 3: m_fdc->tdr_w(data); break;
	case 4: m_fdc->dsr_w(data); break;
	case 5: m_fdc->fifo_w(data); break;
	case 7: m_fdc->ccr_w(data); break;
	default: break;
	}
}

u32 noname_state::sparse_io_r(offs_t offset, u32 mem_mask)
{
	unsigned const port = offset >> 3;
	unsigned const lane = (port & 3) * 8;

	// the ide data register is the only port read wider than a byte
	if (port == 0x1f0 && (offset & 7))
	{
		u32 data = m_ata->cs0_r(0);

		if ((offset & 7) > 3)
			data |= u32(m_ata->cs0_r(0)) << 16;

		return data << lane;
	}

	u8 data = 0;

	switch (port & ~7)
	{
	case 0x1f0: data = m_ata->cs0_r(port & 7); break;
	case 0x00: case 0x08: data = m_dma[0]->read(port & 0xf); break;
	case 0x20: data = m_pic[0]->read(port & 1); break;
	case 0x40: data = m_pit->read(port & 3); break;
	case 0x60: data = m_kbdc->data_r(port & 7); break;
	case 0x70: data = (port & 1) ? m_rtc->data_r() : 0; break;
	case 0x80: case 0x88: data = dma_page_r(port); break;
	case 0xa0: data = m_pic[1]->read(port & 1); break;
	case 0xc0: case 0xc8: case 0xd0: case 0xd8:
		data = m_dma[1]->read((port >> 1) & 0xf);
		break;
	case 0x3b0: case 0x3b8: case 0x3c0: case 0x3c8: case 0x3d0: case 0x3d8:
		data = m_vga_io->read8(port - 0x3b0);
		break;
	case 0x2f8: data = m_uart[1]->ins8250_r(port & 7); break;
	case 0x3f0:
		data = ((port & 7) == 6) ? m_ata->cs1_r(6) : fdc_r(port & 7);
		break;
	case 0x3f8: data = m_uart[0]->ins8250_r(port & 7); break;
	default:
		LOG("io_r %03x (%s)\n", port, machine().describe_context());
		break;
	}

	return u32(data) << lane;
}

void noname_state::sparse_io_w(offs_t offset, u32 data, u32 mem_mask)
{
	unsigned const port = offset >> 3;

	unsigned const lane = (port & 3) * 8;

	if (port == 0x1f0 && (offset & 7))
	{
		m_ata->cs0_w(0, u16(data >> lane));

		if ((offset & 7) > 3)
			m_ata->cs0_w(0, u16(data >> (lane + 16)));

		return;
	}

	u8 const byte = u8(data >> lane);

	switch (port & ~7)
	{
	case 0x1f0: m_ata->cs0_w(port & 7, byte); break;
	case 0x00: case 0x08: m_dma[0]->write(port & 0xf, byte); break;
	case 0x20: m_pic[0]->write(port & 1, byte); break;
	case 0x40: m_pit->write(port & 3, byte); break;
	case 0x60: m_kbdc->data_w(port & 7, byte); break;
	case 0x70: (port & 1) ? m_rtc->data_w(byte) : m_rtc->address_w(byte); break;
	case 0x80: case 0x88: dma_page_w(port, byte); break;
	case 0xa0: m_pic[1]->write(port & 1, byte); break;
	case 0xc0: case 0xc8: case 0xd0: case 0xd8:
		m_dma[1]->write((port >> 1) & 0xf, byte);
		break;
	case 0x3b0: case 0x3b8: case 0x3c0: case 0x3c8: case 0x3d0: case 0x3d8:
		m_vga_io->write8(port - 0x3b0, byte);
		break;
	case 0x2f8: m_uart[1]->ins8250_w(port & 7, byte); break;
	case 0x3f0:
		if ((port & 7) == 6)
			m_ata->cs1_w(6, byte);
		else
			fdc_w(port & 7, byte);
		break;
	case 0x3f8: m_uart[0]->ins8250_w(port & 7, byte); break;
	default:
		LOG("io_w %03x 0x%02x (%s)\n", port, byte, machine().describe_context());
		break;
	}
}

void noname_state::noname(machine_config &config)
{
	DEC_21064(config, m_cpu, 166'000'000);
	m_cpu->set_post_params(ABOX_CTL_INIT, 32 * 1024 * 1024);
	m_cpu->set_dasm_type(alpha_disassembler::dasm_type::TYPE_UNIX);
	m_cpu->set_addrmap(0, &noname_state::local_memory);
	m_cpu->set_addrmap(2, &noname_state::local_io);
	m_cpu->set_addrmap(4, &noname_state::pci_memory);

	RAM(config, m_ram);
	m_ram->set_default_size("32M");
	m_ram->set_extra_options("16M,64M,128M");
	m_ram->set_default_value(0);

	PIC8259(config, m_pic[0]);
	m_pic[0]->out_int_callback().set_inputline(m_cpu, INPUT_LINE_IRQ1);
	m_pic[0]->in_sp_callback().set_constant(1);
	m_pic[0]->read_slave_ack_callback().set(
		[this] (offs_t offset) { return (offset == 2) ? m_pic[1]->acknowledge() : 0; });

	PIC8259(config, m_pic[1]);
	m_pic[1]->out_int_callback().set(m_pic[0], FUNC(pic8259_device::ir2_w));
	m_pic[1]->in_sp_callback().set_constant(0);

	MC146818(config, m_rtc, 32.768_kHz_XTAL);
	m_rtc->irq().set_inputline(m_cpu, INPUT_LINE_IRQ2);

	PIT8254(config, m_pit);
	m_pit->set_clk<0>(14.318181_MHz_XTAL / 12);
	m_pit->out_handler<0>().set(m_pic[0], FUNC(pic8259_device::ir0_w));
	m_pit->set_clk<1>(14.318181_MHz_XTAL / 12);
	m_pit->set_clk<2>(14.318181_MHz_XTAL / 12);

	EISA_DMA(config, m_dma[0], 14.318181_MHz_XTAL / 3);
	m_dma[0]->out_hreq_callback().set(m_dma[1], FUNC(eisa_dma_device::dreq0_w));
	m_dma[0]->in_memr_callback().set(
		[this] (offs_t offset) { return m_cpu->space(0).read_byte(offset); });
	m_dma[0]->out_memw_callback().set(
		[this] (offs_t offset, u8 data) { m_cpu->space(0).write_byte(offset, data); });
	m_dma[0]->in_ior_callback<2>().set(m_fdc, FUNC(n82077aa_device::dma_r));
	m_dma[0]->out_iow_callback<2>().set(m_fdc, FUNC(n82077aa_device::dma_w));
	m_dma[0]->out_eop_callback().set(m_fdc, FUNC(n82077aa_device::tc_line_w));

	EISA_DMA(config, m_dma[1], 14.318181_MHz_XTAL / 3);
	m_dma[1]->out_hreq_callback().set(m_dma[1], FUNC(eisa_dma_device::hack_w));
	m_dma[1]->in_memr_callback().set(
		[this] (offs_t offset) { return m_cpu->space(0).read_byte(offset); });
	m_dma[1]->out_memw_callback().set(
		[this] (offs_t offset, u8 data) { m_cpu->space(0).write_byte(offset, data); });
	m_dma[1]->out_dack_callback<0>().set(m_dma[0], FUNC(eisa_dma_device::hack_w)).invert();

	screen_device &screen(SCREEN(config, "screen"));
	screen.set_raw(25.175_MHz_XTAL, 800, 0, 640, 524, 0, 480);
	screen.set_screen_update(m_vga, FUNC(vga_device::screen_update));

	VGA(config, m_vga, 0);
	m_vga->set_screen("screen");
	m_vga->set_vram_size(0x100000);

	ADDRESS_MAP_BANK(config, m_vga_io);
	m_vga_io->set_map(&noname_state::vga_io);
	m_vga_io->set_options(ENDIANNESS_LITTLE, 8, 8, 0x100);

	KBDC8042(config, m_kbdc);
	m_kbdc->set_keyboard_type(kbdc8042_device::KBDC8042_STANDARD);
	m_kbdc->set_keyboard_tag("kbd");
	m_kbdc->input_buffer_full_callback().set(m_pic[0], FUNC(pic8259_device::ir1_w));

	at_keyboard_device &kbd(AT_KEYB(config, "kbd", pc_keyboard_device::KEYBOARD_TYPE::AT, 1));
	kbd.keypress().set(m_kbdc, FUNC(kbdc8042_device::keyboard_w));

	ATA_INTERFACE(config, m_ata).options(ata_devices, "hdd", nullptr, false);
	m_ata->irq_handler().set(m_pic[1], FUNC(pic8259_device::ir6_w));

	N82077AA(config, m_fdc, 24_MHz_XTAL, n82077aa_device::mode_t::AT);
	m_fdc->intrq_wr_callback().set(m_pic[0], FUNC(pic8259_device::ir6_w));
	m_fdc->drq_wr_callback().set(m_dma[0], FUNC(eisa_dma_device::dreq2_w));
	FLOPPY_CONNECTOR(config, "fdc:0", "35hd", FLOPPY_35_HD, true,
		floppy_image_device::default_pc_floppy_formats).enable_sound(false);

	NS16550(config, m_uart[0], 1.8432_MHz_XTAL);
	NS16550(config, m_uart[1], 1.8432_MHz_XTAL);

	rs232_port_device &com1(RS232_PORT(config, "com1", default_rs232_devices, nullptr));
	m_uart[0]->out_tx_callback().set(com1, FUNC(rs232_port_device::write_txd));
	m_uart[0]->out_dtr_callback().set(com1, FUNC(rs232_port_device::write_dtr));
	m_uart[0]->out_rts_callback().set(com1, FUNC(rs232_port_device::write_rts));
	m_uart[0]->out_int_callback().set(m_pic[0], FUNC(pic8259_device::ir4_w));
	com1.rxd_handler().set(m_uart[0], FUNC(ns16550_device::rx_w));
	com1.cts_handler().set(m_uart[0], FUNC(ns16550_device::cts_w));
	com1.dsr_handler().set(m_uart[0], FUNC(ns16550_device::dsr_w));
	com1.dcd_handler().set(m_uart[0], FUNC(ns16550_device::dcd_w));

	rs232_port_device &com2(RS232_PORT(config, "com2", default_rs232_devices, nullptr));
	m_uart[1]->out_tx_callback().set(com2, FUNC(rs232_port_device::write_txd));
	m_uart[1]->out_int_callback().set(m_pic[0], FUNC(pic8259_device::ir3_w));
	com2.rxd_handler().set(m_uart[1], FUNC(ns16550_device::rx_w));
}

