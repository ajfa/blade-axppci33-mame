/*
 * There is no video bios on the board, so the card is left the way one would
 * leave it: eighty by twenty five text, the sixteen text colours in the ramdac
 * and the character generator loaded into the third plane.
 */
void noname_state::vga_post()
{
	static u8 const seq[] = { 0x03, 0x00, 0x03, 0x00, 0x02 };
	static u8 const crtc[] =
	{
		0x5f, 0x4f, 0x50, 0x82, 0x55, 0x81, 0xbf, 0x1f,
		0x00, 0x4f, 0x0d, 0x0e, 0x00, 0x00, 0x00, 0x00,
		0x9c, 0x8e, 0x8f, 0x28, 0x1f, 0x96, 0xb9, 0xa3, 0xff
	};
	static u8 const gc[] = { 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x0e, 0x00, 0xff };
	static u8 const atc[] =
	{
		0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x14, 0x07,
		0x38, 0x39, 0x3a, 0x3b, 0x3c, 0x3d, 0x3e, 0x3f,
		0x0c, 0x00, 0x0f, 0x08, 0x00
	};
	static u8 const dac[16][3] =
	{
		{  0,  0,  0 }, {  0,  0, 42 }, {  0, 42,  0 }, {  0, 42, 42 },
		{ 42,  0,  0 }, { 42,  0, 42 }, { 42, 21,  0 }, { 42, 42, 42 },
		{ 21, 21, 21 }, { 21, 21, 63 }, { 21, 63, 21 }, { 21, 63, 63 },
		{ 63, 21, 21 }, { 63, 21, 63 }, { 63, 63, 21 }, { 63, 63, 63 }
	};

	auto const io_w = [this] (unsigned port, u8 data) { m_vga_io->write8(port - 0x3b0, data); };
	auto const indexed_w = [&io_w] (unsigned port, unsigned index, u8 data)
	{
		io_w(port, index);
		io_w(port + 1, data);
	};

	io_w(0x3c2, 0x67);

	for (unsigned i = 0; i < std::size(seq); i++)
		indexed_w(0x3c4, i, seq[i]);

	// the horizontal and vertical totals are write protected by the top bit of
	// register 0x11, which the mode itself puts back on its way past
	indexed_w(0x3d4, 0x11, crtc[0x11] & 0x7f);
	for (unsigned i = 0; i < std::size(crtc); i++)
		indexed_w(0x3d4, i, crtc[i]);

	for (unsigned i = 0; i < std::size(gc); i++)
		indexed_w(0x3ce, i, gc[i]);

	// the attribute controller takes its index and its data through one port,
	// and the register that says which is next is reset by reading the status
	m_vga_io->read8(0x3da - 0x3b0);
	for (unsigned i = 0; i < std::size(atc); i++)
	{
		io_w(0x3c0, i);
		io_w(0x3c0, atc[i]);
	}
	io_w(0x3c0, 0x20);

	io_w(0x3c6, 0xff);
	for (unsigned i = 0; i < std::size(dac); i++)
	{
		io_w(0x3c8, atc[i]);
		for (unsigned c = 0; c < 3; c++)
			io_w(0x3c9, dac[i][c]);
	}

	// the character generator is only reachable with the planes addressed one
	// by one instead of interleaved, and the whole window mapped low
	indexed_w(0x3c4, 0x02, 0x04);
	indexed_w(0x3c4, 0x04, 0x06);
	indexed_w(0x3ce, 0x04, 0x02);
	indexed_w(0x3ce, 0x05, 0x00);
	indexed_w(0x3ce, 0x06, 0x00);

	for (unsigned ch = 0; ch < 256; ch++)
	{
		u8 const *const glyph = vga_glyph(ch);

		for (unsigned row = 0; row < 16; row++)
			m_vga->mem_w(ch * 32 + row, glyph ? glyph[row] : 0);
	}

	indexed_w(0x3c4, 0x02, seq[2]);
	indexed_w(0x3c4, 0x04, seq[4]);
	indexed_w(0x3ce, 0x04, gc[4]);
	indexed_w(0x3ce, 0x05, gc[5]);
	indexed_w(0x3ce, 0x06, gc[6]);
}

