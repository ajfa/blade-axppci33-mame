static u8 const *vga_glyph(unsigned ch)
{
	if (ch >= 0x20 && ch < 0x80)
		return &VGA_FONT[(ch - 0x20) * 16];
	else if (ch >= 0xa0)
		return &VGA_FONT[(ch - 0xa0 + 96) * 16];
	else
		return nullptr;
}


